export function exerciseImages(id: string): { frames: [string, string]; approx: boolean } | null {
  const hit = EXERCISE_IMAGES[id];
  if (!hit) return null;
  const base = `/fit/exercicios/${hit.src}`;
  return { frames: [`${base}/0.webp`, `${base}/1.webp`], approx: !!hit.approx };
}

